#include "epd_gray.h"

#include <string.h>

void epd_gray_planes(const uint8_t *src, size_t px, uint8_t *dtm1, uint8_t *dtm2)
{
    for (size_t o = 0; o < px / 8; o++) {
        /* 8 pixels = 2 source bytes; inverted gray i = 3 - g: DTM1 = bit 1 of i, DTM2 = bit 0 */
        uint16_t v = (uint16_t)(~((src[2 * o] << 8) | src[2 * o + 1]) & 0xffff);
        uint8_t hi = 0, lo = 0;
        for (int k = 0; k < 8; k++) {
            unsigned p = (v >> (14 - 2 * k)) & 3;
            hi = (uint8_t)(hi << 1 | (p >> 1));
            lo = (uint8_t)(lo << 1 | (p & 1));
        }
        if (dtm1)
            dtm1[o] = hi;
        if (dtm2)
            dtm2[o] = lo;
    }
}

