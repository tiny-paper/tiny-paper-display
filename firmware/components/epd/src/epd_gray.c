void epd_gray_luts(uint8_t out[EPD_LUT_N][EPD_LUT_LEN])
{
    for (int i = 0; i < EPD_LUT_N; i++) {
        memset(out[i], 0, EPD_LUT_LEN);
        memcpy(out[i], GRAY_LUT[i], sizeof GRAY_LUT[i]);
    }
}
