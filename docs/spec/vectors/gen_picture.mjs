// Vectors of the picture preparation: picture-prepare.json, made by the Picture page's own code (site/picture.js) and read
// by site/test/picture-vectors.test.mjs and python/tests/test_picture.py, so that the web page and Python give the same pixels.
// Run: node docs/spec/vectors/gen_picture.mjs [--check]   (needs `npm ci --prefix site` only for the bundle build, not for this)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_SETTINGS, preparePicture } from '../../../site/picture.js';

const OUT = join(dirname(fileURLToPath(import.meta.url)), 'picture-prepare.json');
const hex = (a) => Buffer.from(a).toString('hex');

/** A deterministic RGBA picture: colour ramps with a diagonal and some transparent and half transparent pixels. */
function source(name, w, h, alpha) {
  const rgba = new Uint8Array(w * h * 4);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const i = (y * w + x) * 4;
    rgba[i] = Math.round(255 * x / Math.max(1, w - 1));
    rgba[i + 1] = Math.round(255 * y / Math.max(1, h - 1));
    rgba[i + 2] = (x * 37 + y * 91) % 256;
    rgba[i + 3] = alpha && (x + y) % 7 === 0 ? 0 : alpha && (x * y) % 5 === 3 ? 128 : 255;
  }
  return { name, w, h, rgba: hex(rgba) };
}
const SOURCES = [source('wide', 12, 5, false), source('tall', 5, 11, false), source('alpha', 9, 9, true), source('big', 23, 17, false)];
const PANELS = { a: { w: 8, h: 6 }, b: { w: 7, h: 9 }, c: { w: 16, h: 8 } };

const CASES = [];
const add = (src, panel, over) => CASES.push({ src, panel, over });
for (const fit of ['fit', 'fill', 'stretch']) for (const src of ['wide', 'tall', 'alpha']) add(src, 'a', { fit, dither: 'none', depth: 4 });
for (const border of ['white', 'black']) for (const src of ['wide', 'alpha']) add(src, 'b', { fit: 'fit', border, dither: 'none', depth: 2 });
for (const rotate of ['auto', 0, 90, 180, 270]) add('tall', 'c', { rotate, dither: 'none', depth: 4 });
for (const depth of [1, 2, 4]) for (const dither of ['floyd', 'ordered', 'none']) for (const src of ['big', 'alpha']) add(src, 'c', { depth, dither });
for (const threshold of [60, 128, 200]) add('big', 'a', { dither: 'none', depth: 1, threshold });
for (const dither of ['floyd', 'ordered', 'none']) for (const src of ['big', 'tall']) add(src, 'a', { color: true, depth: 2, dither });
add('big', 'c', { fit: 'fill', border: 'black', rotate: 'auto', depth: 4, dither: 'floyd' });

const cases = CASES.map(({ src, panel, over }, n) => {
  const s = SOURCES.find((x) => x.name === src), p = PANELS[panel];
  const settings = { ...DEFAULT_SETTINGS, ...over };
  const pic = preparePicture({ w: s.w, h: s.h, rgba: Uint8ClampedArray.from(Buffer.from(s.rgba, 'hex')) }, p, settings);
  return { id: `${n}`, src, panel: p, settings, rotation: pic.rotation, levels: hex(pic.levels) };
});
const text = JSON.stringify({ doc: 'Generated by gen_picture.mjs from site/picture.js: do not edit. levels: one hex byte per panel pixel.', sources: SOURCES, cases }, null, 1) + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== text) { console.error('picture-prepare.json is not what gen_picture.mjs makes'); process.exit(1); }
} else writeFileSync(OUT, text);
