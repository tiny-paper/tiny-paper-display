export const GLYPH_W = 6; // 5 columns and one of space
export const GLYPH_H = 7;
/** Width in pixels of `text` at `scale`. */
export const textWidth = (text: string, scale: number): number => Math.max(0, text.length * GLYPH_W * scale - scale);

/** Call `dot(x, y)` for every pixel of `text` with its top left at x, y. */
export function drawText(text: string, x: number, y: number, scale: number, dot: (x: number, y: number) => void): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const rows = (G[ch] ?? G['?']!).split('/');
    rows.forEach((row, r) => { for (let c = 0; c < 5; c++) if (row[c] === '#') for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) dot(cx + c * scale + dx, y + r * scale + dy); });
    cx += GLYPH_W * scale;
  }
}
